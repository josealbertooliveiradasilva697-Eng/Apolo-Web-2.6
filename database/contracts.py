"""Operações de persistência efetivamente consumidas pelos serviços."""

from typing import Any, Protocol

Linha = dict[str, Any]
Valores = dict[str, float]
IdExecucao = int | str


class RepositorioCalculos(Protocol):
    @property
    def contexto(self) -> str:
        """Identidade estável para separar formulários e resultados."""
        ...

    def variaveis(self) -> list[Linha]: ...
    def salvar_execucao(self, id_calculo: str, entradas: Valores, saidas: Valores) -> IdExecucao: ...
    def configurar(self, nome: str, valor: float | str) -> None: ...
    def historico(self, limite: int = 200) -> list[Linha]: ...
    def detalhe(self, id_execucao: IdExecucao) -> list[Linha]: ...
    def diagnostico(self) -> Linha: ...
